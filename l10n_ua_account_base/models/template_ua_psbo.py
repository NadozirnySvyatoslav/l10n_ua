def stock_account_analytics():
    """{код стокового рахунку: значення полів аналітики}."""
    values = {}
    for codes, analytics in ((PARTNER_ACCOUNTS, 'partner'),
                             (EMPLOYEE_ACCOUNTS, 'employee'),
                             (PRODUCT_ACCOUNTS, 'product')):
        for code in codes:
            values.setdefault(code, {})['ua_analytics_type'] = analytics
    for code in PRODUCT_ACCOUNTS:
        values[code]['ua_is_quantity'] = True
    for code in CURRENCY_ACCOUNTS:
        values.setdefault(code, {})['ua_is_currency'] = True
    return values


def own_accounts():
    """Рахунки, які цей модуль додає до плану: [(код, значення), …]."""
    accounts = [(code, {
        'name': name,
        'account_type': 'off_balance',
        'reconcile': False,
        'ua_analytics_type': analytics,
    }) for code, name, analytics in OFFBALANCE_ACCOUNTS]
    accounts += [(code, {
        'name': name,
        'account_type': account_type,
        'reconcile': reconcile,
        'ua_analytics_type': analytics,
    }) for code, name, account_type, reconcile, analytics in PSBO_EXTRA_ACCOUNTS]
    return accounts


class AccountChartTemplate(models.AbstractModel):
    _inherit = 'account.chart.template'

    @template('ua_psbo', 'account.account')
    def _get_ua_psbo_offbalance_account_account(self):
        data = {
            f'ua_psbo_{code}': {'code': code, **values}
            for code, values in own_accounts()
        }
        for code, values in stock_account_analytics().items():
            data[f'ua_psbp_{code}'] = dict(values)
        for code, name in PSBO_RENAMES.items():
            data.setdefault(f'ua_psbp_{code}', {}).update({
                'name@uk_UA': name,
            })
        return data

    def _post_load_data(self, template_code, company, template_data):
        result = super()._post_load_data(template_code, company, template_data)
        if template_code == 'ua_psbo':
            # Субконто — окрема модель, її записи шаблон не створює.
            from ..hooks import ensure_account_subconto
            ensure_account_subconto(self.env, company or self.env.company)
        return result
