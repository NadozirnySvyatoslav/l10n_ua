"""Добудувати ієрархію КП-2010 і полагодити дерево на наявних базах.

Два різні борги, обидва невидимі з інтерфейсу.

**Ієрархії немає взагалі** — у базах, які встановились після міграції
20.0.1.0.5 і до появи `post_init_hook`: для них не спрацював жоден зі
шляхів, і класифікатор лишився плоским.

**Ієрархія є, а дерево зламане** — у базах, де ту міграцію застали.
`parent_id` вона проставляла сирим SQL, який не чіпав `parent_path`, тож у
поля лишилось значення з `_auto_init` («id/»). Для `_parent_store`-моделі
це означає, що `child_of` і ієрархічне подання показують не те: сам
`parent_id` правильний, а індекс шляху — ні. Побудова ієрархії цього не
виправить, бо переписувати їй нема чого — значення ті самі.

Тому після звірки ієрархії перераховуємо `parent_path` цілком. Обидва
кроки ідемпотентні.
"""

import logging

from odoo import SUPERUSER_ID, api

_logger = logging.getLogger(__name__)


def migrate(cr, version):
    if not version:
        return
    env = api.Environment(cr, SUPERUSER_ID, {})
    kp2010 = env['hr.kp2010']
    kp2010._l10n_ua_build_hierarchy()
    # Перебудова індексу шляхів: після SQL-міграції він лишився порожнім.
    kp2010._parent_store_compute()
    _logger.info(
        'l10n_ua_hr_base 20.0.1.1.4: ієрархію КП-2010 звірено, parent_path '
        'перебудовано')
