"""Датовані правила безоплатного гарячого харчування (п. 4 Порядку № 305).

Порядок організації харчування у закладах освіти та дитячих закладах
оздоровлення та відпочинку, затв. постановою КМУ від 24.03.2021 № 305.

Пільгові категорії (абзаци 2-9 п. 4) — безоплатне гаряче харчування
відповідно до режиму (кратності) харчування закладу, тобто всі прийоми їжі.
Підстава — документи, що підтверджують право (абз. 12 п. 4).

Безоплатне одноразове харчування (сніданок або обід) незалежно від пільгової
категорії (абз. 10 п. 4), редакції:

* до 04.10.2024 — норми немає;
* з 05.10.2024 (пост. № 1145 від 04.10.2024) — «у закладах загальної середньої
  освіти ... учні початкових класів»;
* з 11.10.2025 (пост. № 1280 від 08.10.2025) — лише «у державних та
  комунальних закладах загальної середньої освіти»;
* з 27.06.2026 (пост. № 809 від 24.06.2026, опубл. «Урядовий кур'єр»
  27.06.2026 № 135) — «учні, які здобувають початкову, базову та профільну
  середню освіту», «з урахуванням спроможності органів місцевого
  самоврядування забезпечити таке харчування».

Рівні повної загальної середньої освіти (ст. 10 Закону «Про повну загальну
середню освіту»): початкова — 1-4 класи, базова — 5-9, профільна — 10-12.
"""
from datetime import date

UNIVERSAL_PRIMARY_FROM = date(2024, 10, 5)      # пост. КМУ № 1145
UNIVERSAL_STATE_ONLY_FROM = date(2025, 10, 11)  # пост. КМУ № 1280
UNIVERSAL_ALL_LEVELS_FROM = date(2026, 6, 27)   # пост. КМУ № 809

PRIMARY_LEVELS = range(1, 5)
ALL_LEVELS = range(1, 13)


def education_level(class_level):
    """Рівень ПЗСО за номером класу: 'primary' / 'basic' / 'profile' / False."""
    if not class_level or class_level < 1 or class_level > 12:
        return False
    if class_level <= 4:
        return 'primary'
    if class_level <= 9:
        return 'basic'
    return 'profile'


def universal_free_levels(on_date, is_state, scope='by_law'):
    """Класи, учні яких мають право на безоплатне одноразове харчування
    за абз. 10 п. 4 Порядку № 305 на дату ``on_date``.

    :param is_state: заклад державної/комунальної форми власності
    :param scope: рішення засновника з урахуванням спроможності ОМС
        (діє лише для редакції з 27.06.2026): 'by_law' — усі рівні,
        'primary' — лише початкова освіта, 'none' — не забезпечується.
    :return: range класів (порожній, якщо права немає)
    """
    if not on_date or on_date < UNIVERSAL_PRIMARY_FROM:
        return range(0)
    if on_date >= UNIVERSAL_STATE_ONLY_FROM and not is_state:
        return range(0)
    if on_date < UNIVERSAL_ALL_LEVELS_FROM:
        return PRIMARY_LEVELS
    if scope == 'none':
        return range(0)
    if scope == 'primary':
        return PRIMARY_LEVELS
    return ALL_LEVELS
