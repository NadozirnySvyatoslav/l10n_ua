"""Одне правило округлення днів невикористаної відпустки (#321).

Ним користуються і наказ про звільнення (hr.order.unused_vacation_days_phrase),
і нарахування компенсації (hr.vacation.balance.calculate_compensation у
Ukraine - HR Holidays). Поки правило живе в одному місці, кількість днів у
наказі й днів, за які нараховано гроші, не може розійтися.

Правило: дробовий залишок округлюється вгору до цілого календарного дня.

Закон («Про відпустки», ст. 24) вимагає компенсувати всі невикористані дні
і порядку округлення не встановлює. Мінсоцполітики радило математичне
округлення (листи від 27.03.2013 № 321/13/84-13, від 28.10.2016
№ 616/13/116-16), за яким 11,3 дня дає 11, тобто 0,3 дня, які працівник
заробив, лишаються без оплати. Округлення вгору такої втрати не допускає:
працівник ніколи не отримує менше, ніж заробив. Умови, кращі за
законодавство, дозволені (ст. 9 КЗпП), тож це правило законне за будь-якого
тлумачення.
"""

import math

# Допуск на похибку float: 12.000000001 — це 12, а не 13.
_FLOAT_TOLERANCE_DIGITS = 6


def compensable_vacation_days(days):
    """Ціла кількість календарних днів для компенсації з дробового залишку.

    0 для нульового чи від'ємного залишку, інакше округлення вгору:
    0.4 -> 1, 11.3 -> 12, 12.0 -> 12.
    """
    days = round(days or 0.0, _FLOAT_TOLERANCE_DIGITS)
    if days <= 0:
        return 0
    return math.ceil(days)
